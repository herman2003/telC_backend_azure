-- `total_seats` has never been only seats since `kind` arrived: it counts exam
-- slots today and will count whatever the next center product sells. Renamed
-- while seats are still the only thing in it.
--
-- Written by hand. `migrate diff` produces DROP COLUMN + ADD COLUMN for a
-- rename, which would discard the quantity of every payment ever made.
-- NOT zero-downtime, deliberately. `npm start` runs `migrate deploy` in the
-- new container while the old one is still serving, so between this rename
-- and the cutover the old code's reads of `total_seats` fail. Seconds, on a
-- demo with no paying centers.
--
-- Once centers are really paying, a rename like this needs expand/contract:
-- add the new column, backfill, write both, cut reads over, drop the old one
-- a release later. Doing that now would be four deployments to spare a demo
-- a few seconds of 500s.
ALTER TABLE "payments" RENAME COLUMN "total_seats" TO "quantity";
